pub static mut FB_PTR: *mut u8 = core::ptr::null_mut();
pub static mut FB_PITCH: usize = 0;
pub static mut FB_BPP: usize = 0;

pub fn emergency_fill(color: u32) {
    unsafe {
        if FB_PTR.is_null() { return; }
        let r = ((color >> 16) & 0xFF) as u8;
        let g = ((color >> 8) & 0xFF) as u8;
        let b = (color & 0xFF) as u8;
        // Riempiamo una zona sicura (i primi 500.000 byte)
        for i in 0..500000 {
            *(FB_PTR.add(i)) = b;
            if i % 3 == 1 { *(FB_PTR.add(i)) = g; }
            if i % 3 == 2 { *(FB_PTR.add(i)) = r; }
        }
    }
}

pub fn draw_char(fb_ptr: *mut u8, pitch: usize, bpp: usize, x: usize, y: usize, c: u8, color: u32) {
    if c >= 128 { return; }
    let glyph = FONT[c as usize];
    let r = ((color >> 16) & 0xFF) as u8;
    let g = ((color >> 8) & 0xFF) as u8;
    let b = (color & 0xFF) as u8;

    for row in 0..8 {
        for col in 0..8 {
            if (glyph[row] >> (7 - col)) & 1 == 1 {
                let px = x + col;
                let py = y + row;
                let offset = py * pitch + px * bpp;
                unsafe {
                    *(fb_ptr.add(offset)) = b;
                    *(fb_ptr.add(offset + 1)) = g;
                    *(fb_ptr.add(offset + 2)) = r;
                }
            }
        }
    }
}

pub fn draw_string(fb_ptr: *mut u8, pitch: usize, bpp: usize, x: usize, y: usize, s: &str, color: u32) {
    let mut current_x = x;
    for c in s.as_bytes() {
        let mut char_to_draw = *c;
        if char_to_draw >= b'a' && char_to_draw <= b'z' {
            char_to_draw -= 32; // Trasforma in maiuscolo se non abbiamo le minuscole
        }
        draw_char(fb_ptr, pitch, bpp, current_x, y, char_to_draw, color);
        current_x += 10;
    }
}

pub fn draw_hex(fb: *mut u8, pitch: usize, bpp: usize, x: usize, y: usize, val: u64, color: u32) {
    let mut temp = val;
    let mut buffer = [b'0'; 18];
    buffer[0] = b'0';
    buffer[1] = b'x';
    
    for i in (0..16).rev() {
        let digit = (temp & 0xF) as u8;
        buffer[i + 2] = if digit < 10 { b'0' + digit } else { b'A' + (digit - 10) };
        temp >>= 4;
    }
    
    if let Ok(s) = core::str::from_utf8(&buffer) {
        draw_string(fb, pitch, bpp, x, y, s, color);
    }
}
